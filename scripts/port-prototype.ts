/**
 * Ports the prototype's design to the web application (client 2026-10-03: "design the pages as it
 * is like prototype"; 2026-10-26: the Ocean Living look; 2026-10-27: prototype v4, the blue
 * navigation and dashboard refresh). Reads the client's prototype (read-only input) and writes:
 *
 * - src/theme/campusone.css — the prototype's stylesheet, rule for rule, without its demo chrome
 *   (surface switcher, persona picker, journeys) and its member-app sections (the phone app is
 *   React Native). Colour tokens stay in src/theme/tokens.css (the shared master).
 * - src/theme/campusone-ocean.css — the stylesheet's closing layers, from "THEME — Ocean" on: the
 *   palette, the colourful skin, the motion, the blue navigation & dashboard refresh (collapsible
 *   menu, icon rail, task cards) and the living motion. Written apart so the build can load
 *   src/theme/portal.css (the SaaS portal, which this prototype no longer carries) between the
 *   two, where the earlier prototype had it.
 * - src/components/Utils/icons.ts — the prototype's icon set (RP.IP), with the icons its modules
 *   add later (`RP.IP.sidebar = '…'`).
 *
 * The prototype's two presentation helpers (98_pro_motion.js, 97_ocean_fx.js) are ported by hand
 * in src/components/Utils/motion-fx.ts.
 *
 *   npx tsx scripts/port-prototype.ts ["<path to CampusOne_Prototype_v4.html>"]
 *   npx tsx scripts/port-prototype.ts --check   (fails when the committed files are stale)
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const args = process.argv.slice(2);
const check = args.includes('--check');
const source =
  args.find((a) => !a.startsWith('--')) ??
  join(ROOT, '..', '..', 'Documents', 'CampusOne_Prototype_v4.html');

const html = readFileSync(source, 'utf8');

// ---- stylesheet ---------------------------------------------------------------------------------
const styles = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1] ?? '');
const design = styles.find((s) => s.includes('CampusOne design system'));
if (!design) throw new Error('the prototype design-system stylesheet was not found');
const lines = design.split('\n');
const at = (prefix: string, from = 0) => {
  const i = lines.findIndex((l, n) => n >= from && l.startsWith(prefix));
  if (i < 0) throw new Error(`section not found: ${prefix}`);
  return i;
};
const tokens = at(':root{');
const base = at('*,*::before,*::after{box-sizing:border-box}');
const demo = at('/* ================= DEMO CHROME');
const consoleSec = at('/* ================= CONSOLE / BACK OFFICE');
const memberCampus = at('/* ================= MEMBER APP · campus life');
const instConsole = at('/* ================= INSTITUTION CONSOLE — sign-in');
// The banner's opening line ("/* ====…") sits just above its title.
const ocean = at('   THEME — Ocean') - 1;
const keep: [number, number][] = [
  [0, tokens], // the header comment
  [base, demo], // base, type, layout, buttons, chips, cards, lists, forms, overlays
  [consoleSec, memberCampus], // console and back office shell, terminals, public page
  [instConsole, ocean], // console modules, back office, terminals, admission
];
const css = `/*
 * GENERATED by scripts/port-prototype.ts from the client's prototype — do not edit by hand.
 * The prototype's stylesheet, rule for rule, without its demo chrome and member-app sections.
 * Colour, type and radius tokens come from src/theme/tokens.css (shared master src/theme/tokens.ts);
 * only the stage colours that the back-office panels use are added here. The Ocean layers follow
 * in campusone-ocean.css.
 */
:root{--stage:#0B1E22;--stage-2:#12292E;--stage-line:#23434A;--stage-ink:#D6E7E9;--stage-ink-2:#8FB0B5}
@media (prefers-color-scheme: dark){:root:not([data-theme="light"]){--stage:#050D0F;--stage-2:#0B181B;--stage-line:#1C3339}}
:root[data-theme="dark"]{--stage:#050D0F;--stage-2:#0B181B;--stage-line:#1C3339}
${keep.map(([a, b]) => lines.slice(a, b).join('\n')).join('\n')}

/* ---------- CampusOne web: each surface fills the browser window (no demo stage) ---------- */
body{background:var(--bg)}
rp-root{display:block;height:100%}
.c-app{height:100vh;height:100dvh}
`;
const oceanCss = `/*
 * GENERATED by scripts/port-prototype.ts from the client's prototype — do not edit by hand.
 * The closing layers of the prototype's stylesheet, rule for rule: the Ocean palette and colourful
 * skin, the motion layer, then the blue navigation & dashboard refresh (palette, the parent/subtask
 * menu .nv-*, the icon rail, the task cards .tl-*) and the living motion. Rules for the demo stage
 * and the member app are inert here. The classes the motion layer keys on (rp-swap, rp-open,
 * rp-spot …) are set by src/components/Utils/motion-fx.ts.
 */
${lines.slice(ocean).join('\n')}`;

// ---- icons --------------------------------------------------------------------------------------
const start = html.indexOf('const IP = {');
const end = html.indexOf('RP.IP = IP;');
if (start < 0 || end < 0) throw new Error('the prototype icon set (RP.IP) was not found');
const entries = [...html.slice(start, end).matchAll(/([A-Za-z0-9_]+)\s*:\s*'((?:[^'\\]|\\.)*)'/g)];
// Icons the prototype's modules add to the set later (RP.IP.sidebar = '…'); the set's own win.
const known = new Set(entries.map(([, k]) => k));
for (const m of html.matchAll(/\bRP\.IP\.([A-Za-z0-9_]+)\s*=\s*'((?:[^'\\]|\\.)*)'/g)) {
  if (known.has(m[1])) continue;
  known.add(m[1]);
  entries.push(m);
}
const icons = `/**
 * GENERATED by scripts/port-prototype.ts — the prototype's icon set (RP.IP): 24×24 outline paths
 * drawn with a round stroke in the current colour. Rendered by components/Shared/Icon.ts.
 */
export const ICON_PATHS = {
${entries.map(([, k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n')}
} as const;

export type IconName = keyof typeof ICON_PATHS;
`;

const outputs: [string, string][] = [
  [join(ROOT, 'src', 'theme', 'campusone.css'), css],
  [join(ROOT, 'src', 'theme', 'campusone-ocean.css'), oceanCss],
  [join(ROOT, 'src', 'components', 'Utils', 'icons.ts'), icons],
];
let stale = false;
for (const [file, text] of outputs) {
  if (check) {
    const current = existsSync(file) ? readFileSync(file, 'utf8') : '';
    if (current !== text) {
      console.error(`stale: ${file} (run npm run prototype:port)`);
      stale = true;
    }
  } else {
    writeFileSync(file, text);
  }
}
if (stale) process.exit(1);
console.log(
  check ? 'prototype port up to date' : `ported ${entries.length} icons and the stylesheet`,
);
